// The edge functions (Deno) reuse the reader's pure TypeScript so that what we
// test is exactly what runs. Deno wants explicit ".ts" extensions on relative
// imports, so this copies the shared modules into supabase/functions/_shared
// with the extensions added. Run `npm run sync:functions` after editing them;
// `npm test` fails if the copies drift.
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";

export const SHARED = ["types", "ingest-schema", "ingest-core", "rows", "brief", "curation", "ledger", "docs", "seed"];

export function rewrite(src) {
  const banner = "// GENERATED by scripts/sync-shared.mjs from src/lib. Do not edit by hand.\n";
  return banner + src.replace(/(from\s+["'])(\.\/[A-Za-z0-9-]+)(["'])/g, "$1$2.ts$3");
}

const root = fileURLToPath(new URL("..", import.meta.url));

export async function build() {
  const out = {};
  for (const name of SHARED) {
    const src = await readFile(`${root}/src/lib/${name}.ts`, "utf8");
    out[`${root}/supabase/functions/_shared/${name}.ts`] = rewrite(src);
  }
  return out;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  await mkdir(`${root}/supabase/functions/_shared`, { recursive: true });
  const files = await build();
  for (const [path, content] of Object.entries(files)) await writeFile(path, content);
  console.log(`synced ${Object.keys(files).length} shared modules`);
}
